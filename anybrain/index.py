"""Indexes and graph.json (PRD section 14).

`anybrain index <vault> [--check] [--stats]` writes the root `index.md`, one `index.md` per domain, and
`.harness/graph.json`. Idempotent: a second run writes nothing. `--check` writes nothing and exits 1 if
any of those files would change (CI). The `generated` timestamp of graph.json is ignored when comparing.
"""
from __future__ import annotations

from pathlib import Path

from . import graph as g
from . import vault as v

HEADER = "<!-- generated by anybrain index; do not edit -->"
ROOT_TITLE = "# brain"
ROOT_BUDGET_LINES = 60

# Group order inside a domain index. Books follow the root-line example of 14.2
# ("31 read, 4 reading, 12 to-read"); projects follow the enum order of 11.5 (D013).
STATUS_ORDER = {
    "book": ["read", "reading", "to-read", "abandoned"],
    "project": ["idea", "active", "paused", "shipped", "dropped"],
}
OTHER_GROUP = "other"


class IndexBuildError(Exception):
    """The vault cannot be indexed (a page without description)."""


def _plural(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


def _updated(page: v.Page) -> str:
    date = v.as_date(page.meta.get("updated"))
    return date.isoformat() if date else ""


def _stars(rating) -> str:
    if isinstance(rating, int) and not isinstance(rating, bool) and 1 <= rating <= 5:
        return "★" * rating
    return ""


def _text(value) -> str | None:
    """A frontmatter value as display text; a list (several authors) is joined with commas."""
    if value is None or value == "":
        return None
    if isinstance(value, (list, tuple)):
        return ", ".join(str(item) for item in value if item not in (None, "")) or None
    return str(value)


def page_line(page: v.Page, link: str, graph: g.Graph, domain: str = "") -> str:
    """One index line in the formats of 14.2.

    A confidential page listed outside a local-only folder (a mission project, a page that declares
    `sensitivity: confidential`) shows its title only, as `neighbors` does (13.5, D025).
    """
    fm = page.meta
    if page.sensitivity == "confidential" and domain not in v.LOCAL_ONLY_FOLDERS:
        return f"- [{page.title}]({link}): {g.CONFIDENTIAL_MARK}"
    head = f"- [{page.title}]({link}): {page.description}"
    if page.type == "book":
        parts = [_text(fm.get("author")), _stars(fm.get("rating")), _text(fm.get("status")), _text(fm.get("date_read"))]
    elif page.type == "concept":
        sources = len(v.as_list(fm.get("sources")))
        inbound = len(graph.nodes[page.rel].inbound)
        parts = [f"confidence {fm.get('confidence', 'low')}", _plural(sources, "source"), _plural(inbound, "in-link")]
    elif page.type == "project":
        review = v.as_date(fm.get("next_review"))
        parts = [_text(fm.get("status")), _text(fm.get("kind")), f"review {review.isoformat()}" if review else None]
    else:
        parts = []
    extra = " · ".join(str(p) for p in parts if p not in (None, ""))
    return f"{head} ({extra})" if extra else head


def _known_statuses(domain_pages: list[v.Page]) -> list[str]:
    order: list[str] = []
    for page_type in ("book", "project"):
        if any(p.type == page_type for p in domain_pages):
            order += [s for s in STATUS_ORDER[page_type] if s not in order]
    return order


def _group_key(page: v.Page, known: list[str]) -> str:
    """The status group of a page; "" when the domain is not grouped; `other` for anything unknown (D013)."""
    if not known:
        return ""
    status = page.meta.get("status") if page.type in STATUS_ORDER else None
    return status if isinstance(status, str) and status in known else OTHER_GROUP


def _group_order(known: list[str], key: str) -> int:
    return known.index(key) if key in known else len(known)


def domain_index(domain: str, pages: list[v.Page], graph: g.Graph) -> str:
    out = [HEADER, f"# {domain}", ""]
    if not pages:
        out += ["No pages yet.", ""]
        return "\n".join(out)
    known = _known_statuses(pages)
    groups: dict[str, list[v.Page]] = {}
    for page in pages:
        groups.setdefault(_group_key(page, known), []).append(page)
    for key in sorted(groups, key=lambda k: _group_order(known, k)):
        members = sorted(groups[key], key=lambda p: p.rel)
        members.sort(key=_updated, reverse=True)
        if key:
            out += [f"## {key}", ""]
        for page in members:
            link = page.rel[len(domain) + 1:]
            out.append(page_line(page, link, graph, domain))
        out.append("")
    return "\n".join(out)


def _domain_summary(pages: list[v.Page]) -> str:
    known = _known_statuses(pages)
    if not known or not pages:
        return _plural(len(pages), "page")
    counts: dict[str, int] = {}
    for page in pages:
        key = _group_key(page, known)
        counts[key] = counts.get(key, 0) + 1
    return ", ".join(f"{counts[k]} {k}" for k in sorted(counts, key=lambda k: _group_order(known, k)))


def root_index(vault: Path, by_domain: dict[str, list[v.Page]]) -> str:
    out = [HEADER, ROOT_TITLE, "", "Navigate: this file, then a domain index, then a page. Never scan the whole vault.", ""]
    for domain, pages in by_domain.items():
        if domain in v.CONFIDENTIAL_FOLDERS:
            out.append(f"- [{domain}]({domain}/index.md): {_plural(len(pages), 'page')}; confidential, local profile only")
            continue
        latest = max((_updated(p) for p in pages), default="")
        tail = f"; last updated {latest}" if latest else ""
        out.append(f"- [{domain}]({domain}/index.md): {_domain_summary(pages)}{tail}")
    if (vault / "log.md").is_file():
        out += ["", "- [log](log.md): changelog, newest at the bottom"]
    out.append("")
    return "\n".join(out)


def build(vault: Path) -> tuple[dict[str, str], g.Graph]:
    """Every generated file as {vault-relative path: content}, plus the graph."""
    pages = v.load_pages(vault)
    problems = []
    for page in pages:
        if page.error:
            problems.append(f"{page.rel}: {page.error}")
        elif not page.description:
            problems.append(f"{page.rel}: no `description` (it becomes the index line)")
    if problems:
        raise IndexBuildError("cannot build the indexes:\n  " + "\n  ".join(problems))
    graph = g.Graph(vault, pages)
    by_domain: dict[str, list[v.Page]] = {}
    for domain in v.DOMAINS:
        if (vault / domain).is_dir():
            by_domain[domain] = [p for p in pages if p.folder == domain]
    files = {f"{domain}/index.md": domain_index(domain, ps, graph) for domain, ps in by_domain.items()}
    files["index.md"] = root_index(vault, by_domain)
    return files, graph


def _tokens(text: str) -> int:
    return len(text.split()) * 4 // 3


def print_stats(files: dict[str, str], graph: g.Graph) -> None:
    stats = graph.stats()
    by_domain: dict[str, int] = {}
    for node in graph.nodes.values():
        by_domain[node.page.folder] = by_domain.get(node.page.folder, 0) + 1
    for domain in v.DOMAINS:
        if f"{domain}/index.md" in files:
            print(f"{domain:<10} {_plural(by_domain.get(domain, 0), 'page'):>9}")
    print(f"edges {stats['edges']}, orphans {stats['orphans']}, broken links {stats['broken']}")
    root_tokens = _tokens(files["index.md"])
    domains = {k: _tokens(c) for k, c in files.items() if k != "index.md"}
    largest = max(domains, key=domains.get) if domains else None
    if largest:
        print(f"root index ~{root_tokens} tokens; largest domain index {largest} ~{domains[largest]} tokens; "
              f"together ~{root_tokens + domains[largest]} tokens")
    else:
        print(f"root index ~{root_tokens} tokens")


def run(vault: Path, check: bool = False, stats: bool = False) -> int:
    try:
        files, graph = build(vault)
    except IndexBuildError as exc:
        print(f"index: {exc}")
        return 1
    changed: list[tuple[str, str]] = []
    for rel, content in files.items():
        path = vault / rel
        if not path.is_file() or v.read_text(path) != content:
            changed.append((rel, content))
    graph_text = g.graph_json_changes(vault, graph)
    if graph_text is not None:
        changed.append((g.GRAPH_FILE, graph_text))
    if root_lines := files["index.md"].count("\n"):
        if root_lines > ROOT_BUDGET_LINES:
            print(f"index: warning: root index is {root_lines} lines (budget {ROOT_BUDGET_LINES})")
    if stats:
        print_stats(files, graph)
    if check:
        for rel, _ in changed:
            print(f"index: would change {rel}")
        print(f"index: {len(changed)} file(s) out of date")
        return 1 if changed else 0
    for rel, content in changed:
        v.write_text(vault / rel, content)
        print(f"wrote {rel}")
    print(f"index: {len(changed)} file(s) written")
    return 0
