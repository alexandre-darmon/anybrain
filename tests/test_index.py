def test_book_concept_project_and_other_lines(make_vault):
    root = make_vault({
        "library/snow.md": page("The Snow Leopard", "book", "How to create a category.", author="Nicolas Cole",
                                status="read", rating=5, date_read="2022-12"),
        "wiki/concepts/cat.md": page("Category design", "concept", "Win by creating the category.",
                                     confidence="medium", sources=["library/snow.md", "library/x.md", "library/y.md"]),
        "wiki/notes/n.md": page("Note", body="builds on [[cat]]"),
        "projects/tool.md": page("Example tool", "project", "A CLI.", status="active", kind="portfolio",
                                 next_review="2026-11-30"),
    })
    files, _ = index.build(root)
    assert "- [The Snow Leopard](snow.md): How to create a category. (Nicolas Cole · ★★★★★ · read · 2022-12)" in files["library/index.md"]
    assert "- [Category design](concepts/cat.md): Win by creating the category. (confidence medium · 3 sources · 1 in-link)" in files["wiki/index.md"]
    assert "- [Note](notes/n.md): Says one thing clearly." in files["wiki/index.md"]
    assert "- [Example tool](tool.md): A CLI. (active · portfolio · review 2026-11-30)" in files["projects/index.md"]


def test_grouped_by_status_and_sorted_by_updated_descending(make_vault):
    root = make_vault({
        "library/old.md": page("Old", "book", author="A", status="read", updated="2026-01-01"),
        "library/new.md": page("New", "book", author="A", status="read", updated="2026-06-01"),
        "library/now.md": page("Now", "book", author="A", status="reading"),
        "library/later.md": page("Later", "book", author="A", status="to-read"),
    })
    text = index.build(root)[0]["library/index.md"]
    assert text.index("## read") < text.index("## reading") < text.index("## to-read")
    assert text.index("[New]") < text.index("[Old]")


def test_root_index_lines_and_confidential_counts(make_vault):
    root = make_vault({
        "library/a.md": page("A", "book", author="A", status="read", updated="2026-11-15"),
        "library/b.md": page("B", "book", author="B", status="to-read", updated="2026-11-01"),
        "company/plan.md": page("Plan", updated="2026-11-14"),
        "journal/2026-11-01.md": page("Brief", "brief"),
        "log.md": "2026-11-01 · init · created vault\n",
    })
    root_text = index.build(root)[0]["index.md"]
    assert "- [library](library/index.md): 1 read, 1 to-read; last updated 2026-11-15" in root_text
    assert "- [company](company/index.md): 1 page; confidential, local profile only" in root_text
    assert "2026-11-14" not in root_text
    assert "- [journal](journal/index.md): 1 page; last updated 2026-01-01" in root_text
    assert "- [log](log.md): changelog, newest at the bottom" in root_text
    assert "Plan" not in root_text


def test_empty_domain_says_so(make_vault):
    root = make_vault({"library/a.md": page("A", "book", author="A", status="read")})
    (root / "projects").mkdir()
    files = index.build(root)[0]
    assert "No pages yet." in files["projects/index.md"]
    assert "- [projects](projects/index.md): 0 pages" in files["index.md"]


def test_root_index_stays_within_budget(make_vault):
    files = {f"library/book-{i:04d}.md": page(f"Book {i}", "book", author="A", status="read") for i in range(300)}
    root = make_vault(files)
    for domain in v.DOMAINS:
        (root / domain).mkdir(exist_ok=True)
    text = index.build(root)[0]["index.md"]
    assert text.count("\n") <= index.ROOT_BUDGET_LINES


