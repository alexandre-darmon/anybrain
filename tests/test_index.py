"""anybrain index: line formats, grouping, golden files, idempotence, --check (PRD 14)."""
from __future__ import annotations

import json
import shutil

from anybrain import cli, index
from anybrain import vault as v
from conftest import EXAMPLE, page

GENERATED = ["index.md", "me/index.md", "library/index.md", "wiki/index.md", "projects/index.md",
             "company/index.md", "finance/index.md", "journal/index.md"]


def run(root, *flags):
    return cli.main(["index", str(root), *flags])


# ---------------------------------------------------------------- acceptance of 14.3

def test_example_golden_files_are_committed_and_up_to_date(capsys):
    assert run(EXAMPLE, "--check") == 0
    assert "0 file(s) out of date" in capsys.readouterr().out


def test_regenerating_the_example_is_byte_identical(example_vault, tmp_path):
    for rel in GENERATED:
        (example_vault / rel).unlink()
    (example_vault / ".harness" / "graph.json").unlink()
    assert run(example_vault) == 0
    for rel in GENERATED:
        assert (example_vault / rel).read_bytes() == (EXAMPLE / rel).read_bytes(), rel
    fresh = json.loads((example_vault / ".harness" / "graph.json").read_text())
    committed = json.loads((EXAMPLE / ".harness" / "graph.json").read_text())
    fresh.pop("generated"), committed.pop("generated")
    assert fresh == committed


def test_running_twice_writes_nothing(example_vault, capsys):
    assert run(example_vault) == 0
    assert "index: 0 file(s) written" in capsys.readouterr().out
    before = {p: p.stat().st_mtime_ns for p in example_vault.rglob("*") if p.is_file()}
    assert run(example_vault) == 0
    after = {p: p.stat().st_mtime_ns for p in example_vault.rglob("*") if p.is_file()}
    assert before == after


def test_check_writes_nothing_and_exits_1_when_stale(example_vault, capsys):
    target = example_vault / "library" / "inspired.md"
    target.write_text(target.read_text().replace("Empowered product teams", "Strong teams"))
    before = (example_vault / "library" / "index.md").read_text()
    assert run(example_vault, "--check") == 1
    out = capsys.readouterr().out
    assert "would change library/index.md" in out
    assert "would change .harness/graph.json" in out
    assert (example_vault / "library" / "index.md").read_text() == before


