#!/usr/bin/env python3
"""Regenerate every index.md in a vault from page frontmatter.

Usage: build_index.py <vault_path> [--stats] [--check]
  --stats  print pages per domain and root-index size
  --check  exit 1 if any index would change (CI mode); write nothing

Reads frontmatter only. Idempotent. Fails on a page without `description`.
Standard library + pyyaml.
"""
import sys, re, datetime
from pathlib import Path
import yaml

DOMAINS = ["me", "wiki", "library", "projects", "company", "finance", "journal"]
SKIP = {"raw", ".harness", ".git", ".obsidian"}
FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)


def frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = FM_RE.match(text)
    if not m:
        raise SystemExit(f"[build_index] no frontmatter: {path}")
    fm = yaml.safe_load(m.group(1)) or {}
    if not fm.get("description"):
        raise SystemExit(f"[build_index] missing description: {path}")
    return fm


def line(fm: dict, rel: str) -> str:
    t = fm.get("type")
    extra = ""
    if t == "book":
        parts = [fm.get("author", "?")]
        if fm.get("rating"):
            parts.append("★" * int(fm["rating"]))
        parts.append(fm.get("status", ""))
        if fm.get("date_read"):
            parts.append(str(fm["date_read"]))
        extra = " · ".join(str(p) for p in parts if p)
    elif t == "project":
        parts = [fm.get("status", ""), fm.get("kind", "")]
        if fm.get("next_review"):
            parts.append(f"review {fm['next_review']}")
        extra = " · ".join(str(p) for p in parts if p)
    elif t == "concept":
        extra = f"confidence {fm.get('confidence', 'low')} · {len(fm.get('sources') or [])} sources"
    tail = f" ({extra})" if extra else ""
    return f"- [{fm['title']}]({rel}) — {fm['description']}{tail}"


def build_domain(vault: Path, domain: str) -> tuple[str, dict]:
    folder = vault / domain
    pages = [p for p in folder.rglob("*.md") if p.name != "index.md"]
    rows, groups, latest = [], {}, None
    for p in pages:
        fm = frontmatter(p)
        rel = p.relative_to(folder).as_posix()
        upd = str(fm.get("updated", ""))
        latest = max(latest or upd, upd)
        key = fm.get("status", "") if fm.get("type") in ("book", "project") else ""
        groups.setdefault(key, []).append((upd, line(fm, rel)))
    out = [f"# {domain}", "", f"<!-- generated by build_index.py — do not edit -->", ""]
    for key in sorted(groups, key=lambda k: (k == "", k)):
        if key:
            out += [f"## {key}", ""]
        out += [l for _, l in sorted(groups[key], reverse=True)]
        out.append("")
    stats = {"pages": len(pages), "latest": latest or "-", "groups": {k: len(v) for k, v in groups.items()}}
    return "\n".join(out).rstrip() + "\n", stats


def build_root(vault: Path, stats: dict) -> str:
    out = ["# brain", "", "<!-- generated by build_index.py — do not edit -->", "",
           "Navigate: this file → a domain index → a page. Never scan the vault.", ""]
    for d in DOMAINS:
        if d not in stats:
            continue
        s = stats[d]
        detail = ", ".join(f"{n} {k}" for k, n in s["groups"].items() if k) or f"{s['pages']} page{'s' if s['pages'] != 1 else ''}"
        out.append(f"- [{d}]({d}/index.md) — {detail}; last updated {s['latest']}")
    out += ["", f"- [log](log.md) — changelog, newest at the bottom", ""]
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    vault = Path(sys.argv[1]).expanduser().resolve()
    check, show = "--check" in sys.argv, "--stats" in sys.argv
    stats, changed = {}, []
    for d in DOMAINS:
        if not (vault / d).is_dir():
            continue
        content, stats[d] = build_domain(vault, d)
        target = vault / d / "index.md"
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            changed.append(target)
            if not check:
                target.write_text(content, encoding="utf-8")
    root = build_root(vault, stats)
    target = vault / "index.md"
    if not target.exists() or target.read_text(encoding="utf-8") != root:
        changed.append(target)
        if not check:
            target.write_text(root, encoding="utf-8")
    if show:
        for d, s in stats.items():
            print(f"{d:10} {s['pages']:4} pages  latest {s['latest']}")
        print(f"root index ~{len(root.split()) * 4 // 3} tokens")
    if check and changed:
        print("[build_index] stale:", *[p.relative_to(vault) for p in changed])
        sys.exit(1)
    print(f"[build_index] {len(changed)} index file(s) written")


if __name__ == "__main__":
    main()
